'use strict';
// Conservative first aid only; no diagnosis, medicines, antidotes or induced vomiting.
const SAFETY='หยุดสัมผัสสารและขอความช่วยเหลือทันทีค่ะ หากหายใจลำบาก ชัก หรือหมดสติ โทร 1669 และติดต่อศูนย์พิษวิทยา 1367 พร้อมชื่อสารหรือฉลาก ห้ามทำให้อาเจียนเอง';
function isExposure(text) {
 return /(?:สาร|ยา|น้ำยา|ยาฆ่าแมลง|ยาฆ่าหญ้า).{0,25}(?:เข้าตา|เข้าปาก|โดนผิว|โดนตัว|หกรด|สูด|กลืน|กินเข้า)|(?:กิน|กลืน|เลีย|สูดดม|เผลอกิน).{0,20}(?:สาร|ยาฆ่า|น้ำยา)|(?:ฉีด|พ่น).{0,10}(?:ยา|สาร).{0,30}(?:เวียนหัว|หายใจไม่ออก|แน่นหน้าอก|อาเจียน|คลื่นไส้|แสบตา)|(?:สาร|ยา)เข้าตา|(?:สาร|ยา).{0,8}(?:กระเด็น|หก).{0,12}(?:ตา|ผิว|แขน)|(?:หมา|สุนัข|แมว|สัตว์|วัว|ควาย).{0,20}(?:ได้รับสาร|สัมผัสสาร|กินยา|เลียยา)/.test(text);
}
function exposureAnswer(text) {
 if(/หมา|สุนัข|แมว|สัตว์|วัว|ควาย/.test(text))return 'กันสัตว์ออกจากบริเวณสารและรีบติดต่อสัตวแพทย์หรือโรงพยาบาลสัตว์ทันทีค่ะ นำฉลากหรือชื่อสารไปด้วย อย่าทำให้อาเจียนหรือป้อนยาแก้พิษเอง และระวังไม่ให้ผู้ช่วยสัมผัสสาร';
 let extra='';
 if(/ตา/.test(text))extra=' ล้างตาด้วยน้ำสะอาดไหลเบา ๆ อย่างน้อย 15 นาที อย่าขยี้ตา แล้วรีบพบแพทย์';
 else if(/ผิว|โดนตัว|หกรด|แขน/.test(text))extra=' ถอดเสื้อผ้าที่เปื้อนอย่างระมัดระวัง ล้างผิวด้วยน้ำและสบู่ปริมาณมาก';
 else if(/สูด|ดม/.test(text))extra=' ออกจากบริเวณสารไปที่อากาศถ่ายเทโดยไม่เสี่ยงให้ผู้ช่วยสัมผัสสาร';
 return SAFETY+extra;
}
module.exports={isExposure,SAFETY,exposureAnswer};
